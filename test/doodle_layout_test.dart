import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:serafim/src/utils/chat/doodle_layout.g.dart';
import 'package:serafim/src/utils/chat/doodle_packing.dart';

/// The wallpaper layout is packed once, ahead of time, and stored in
/// `doodle_layout.g.dart`. This test regenerates it on request, and otherwise
/// checks the stored copy still matches what the packing code produces — so a
/// change to a doodle or to the packer can't silently alter (or break) the
/// approved look.
void main() {
  final write = Platform.environment['WRITE_DOODLE_LAYOUT'] == '1';

  test(write ? 'WRITE doodle_layout.g.dart' : 'stored layout matches the packer', () {
    final fresh = DoodleLayout.fresh();

    if (write) {
      final b = StringBuffer()
        ..writeln(
          '/// GENERATED by `test/doodle_layout_test.dart` — do not edit by hand.',
        )
        ..writeln(
          '/// Regenerate after changing any doodle or the packer (bounds first):',
        )
        ..writeln(
          '///   WRITE_DOODLE_BOUNDS=1 flutter test test/doodle_bounds_test.dart',
        )
        ..writeln(
          '///   WRITE_DOODLE_LAYOUT=1 flutter test test/doodle_layout_test.dart',
        )
        ..writeln('const double doodleLayoutWidth = ${fresh.width};')
        ..writeln('const double doodleLayoutHeight = ${fresh.height};')
        ..writeln('')
        ..writeln('/// (name, x, y, rotation, scale)')
        ..writeln(
          'const List<(String, double, double, double, double)> doodleLayoutData = [',
        );
      for (final p in fresh.items) {
        String f(double v) => v.toStringAsFixed(3);
        b.writeln(
          "  ('${p.doodle.name}', ${f(p.at.dx)}, ${f(p.at.dy)}, ${f(p.rotation)}, ${f(p.scale)}),",
        );
      }
      b.writeln('];');
      File(
        'lib/src/utils/chat/doodle_layout.g.dart',
      ).writeAsStringSync(b.toString());
      return;
    }

    expect(
      doodleLayoutData.length,
      fresh.items.length,
      reason: 'regenerate the layout',
    );
    expect(doodleLayoutWidth, fresh.width);
    expect(doodleLayoutHeight, fresh.height);
    for (var i = 0; i < fresh.items.length; i++) {
      final f = fresh.items[i];
      final s = doodleLayoutData[i];
      expect(s.$1, f.doodle.name, reason: 'item $i');
      expect((s.$2 - f.at.dx).abs(), lessThan(0.002), reason: '${s.$1} x');
      expect((s.$3 - f.at.dy).abs(), lessThan(0.002), reason: '${s.$1} y');
      expect(
        (s.$4 - f.rotation).abs(),
        lessThan(0.002),
        reason: '${s.$1} rotation',
      );
      expect((s.$5 - f.scale).abs(), lessThan(0.002), reason: '${s.$1} scale');
    }
  });
}
