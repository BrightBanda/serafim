import 'dart:io';
import 'dart:math' as math;
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:serafim/src/utils/chat/doodle_bounds.g.dart';
import 'package:serafim/src/utils/chat/doodle_catalogue.dart';
import 'package:serafim/src/utils/themes/app_colors.dart';

/// Renders [d] and finds the smallest circle that contains all of its ink.
Future<DoodleBounds> measure(Doodle d) async {
  const px = 6.0; // pixels per unit
  const size = 900;
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  canvas.translate(size / 2, size / 2);
  canvas.scale(px);
  d.draw(canvas, DoodleInk(AppPalette.dark));
  final image = await recorder.endRecording().toImage(size, size);
  final data = (await image.toByteData(
    format: ui.ImageByteFormat.rawRgba,
  ))!.buffer.asUint8List();

  final pts = <Offset>[];
  for (var y = 0; y < size; y += 2) {
    for (var x = 0; x < size; x += 2) {
      if (data[(y * size + x) * 4 + 3] >= 8)
        pts.add(Offset(x - size / 2, y - size / 2));
    }
  }
  expect(pts, isNotEmpty, reason: '${d.name} drew nothing');

  // Badoiu-Clarkson: walk a centre toward the farthest point; it converges on
  // the minimum enclosing circle.
  var c = pts.first;
  for (var i = 1; i <= 400; i++) {
    var far = pts.first;
    var farD = 0.0;
    for (final p in pts) {
      final dd = (p - c).distanceSquared;
      if (dd > farD) {
        farD = dd;
        far = p;
      }
    }
    c = c + (far - c) / (i + 1.0);
  }
  var r = 0.0;
  for (final p in pts) {
    r = math.max(r, (p - c).distance);
  }
  // +1.1 units: stroke half-width and anti-aliasing.
  double round(double v) => (v * 10).round() / 10;
  return DoodleBounds(round(c.dx / px), round(c.dy / px), round(r / px + 1.1));
}

void main() {
  final write = Platform.environment['WRITE_DOODLE_BOUNDS'] == '1';

  test(
    write
        ? 'WRITE doodle_bounds.g.dart'
        : 'stored doodle bounds match the drawings',
    () async {
      final measured = <String, DoodleBounds>{};
      for (final d in allDoodles) {
        measured[d.name] = await measure(d);
      }

      if (write) {
        final b = StringBuffer()
          ..writeln("import 'package:serafim/src/utils/chat/doodle_kit.dart';")
          ..writeln()
          ..writeln(
            '/// GENERATED by `test/doodle_bounds_test.dart` — do not edit by hand.',
          )
          ..writeln('/// Regenerate after changing any doodle:')
          ..writeln(
            '///   WRITE_DOODLE_BOUNDS=1 flutter test test/doodle_bounds_test.dart',
          )
          ..writeln('const Map<String, DoodleBounds> doodleBounds = {');
        for (final e in measured.entries) {
          b.writeln(
            "  '${e.key}': DoodleBounds(${e.value.cx}, ${e.value.cy}, ${e.value.radius}),",
          );
        }
        b.writeln('};');
        File(
          'lib/src/utils/chat/doodle_bounds.g.dart',
        ).writeAsStringSync(b.toString());
        return;
      }

      for (final d in allDoodles) {
        final stored = doodleBounds[d.name];
        expect(
          stored,
          isNotNull,
          reason: '${d.name} has no stored bounds — regenerate them',
        );
        final m = measured[d.name]!;
        expect(
          (stored!.cx - m.cx).abs(),
          lessThan(1.0),
          reason: '${d.name} moved; regenerate bounds',
        );
        expect(
          (stored.cy - m.cy).abs(),
          lessThan(1.0),
          reason: '${d.name} moved; regenerate bounds',
        );
        expect(
          (stored.radius - m.radius).abs(),
          lessThan(1.5),
          reason: '${d.name} changed size; regenerate bounds',
        );
      }
    },
  );
}
